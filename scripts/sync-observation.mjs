import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.join(root, "src/features/tasks/observation-components.js");
const manifestPath = path.join(root, "vendor/observation-renderer.json");
const normalize = (text) => text.replace(/\r\n?/g, "\n").trimEnd();
const sha256 = (text) => createHash("sha256").update(normalize(text)).digest("hex");
const sourceIndex = process.argv.indexOf("--source");
const checking = process.argv.includes("--check");

if (sourceIndex >= 0) {
  if (!process.argv[sourceIndex + 1] || process.argv[sourceIndex + 1].startsWith("--"))
    throw new Error("--source requires an explicit renderer source file.");
  const source = path.resolve(process.argv[sourceIndex + 1]);
  const contents = normalize(await readFile(source, "utf8"));
  const generated = `// Generated by scripts/sync-observation.mjs from the backend canonical component renderer.\n${contents}\nexport default globalThis.CWMObservation;\n`;
  if (checking) {
    if (sha256(await readFile(target, "utf8")) !== sha256(generated))
      throw new Error("Observation renderer differs from the explicitly selected source.");
  } else {
    await writeFile(target, generated, "utf8");
    await writeFile(manifestPath, JSON.stringify({ schema: "cwm.observation-renderer.v1", protocolVersion: 1, sourceSha256: sha256(contents), contentSha256: sha256(generated) }, null, 2) + "\n", "utf8");
  }
} else if (!checking) {
  throw new Error("Provide --source <renderer.js> to import a renderer, or --check to validate the packaged copy.");
}

// Client builds validate their versioned artifact without a neighbouring server
// checkout. Maintainers may additionally check against an explicit source above.
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
if (manifest.schema !== "cwm.observation-renderer.v1" || manifest.protocolVersion !== 1 || manifest.contentSha256 !== sha256(await readFile(target, "utf8")))
  throw new Error("Packaged observation renderer failed integrity validation.");
console.log("Observation renderer artifact verified.");
