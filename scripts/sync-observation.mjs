import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.resolve(root, "../../Python/Chat-With-Me-Backend/application/management_pages/static/observation-components.js");
const target = path.join(root, "src/features/tasks/observation-components.js");
const normalize = (text) => text.replace(/\r\n?/g, "\n").trimEnd();
const generated = `// Generated by scripts/sync-observation.mjs from the backend canonical component renderer.\n${normalize(await readFile(source, "utf8"))}\nexport default globalThis.CWMObservation;\n`;
if (process.argv.includes("--check")) {
  if (normalize(await readFile(target, "utf8")) !== normalize(generated)) throw new Error("Observation renderer is stale; run node scripts/sync-observation.mjs.");
} else await writeFile(target, generated, "utf8");
